let totalWorldLock = 0;
let totalSSP = 0;

$(document).ready(function () {
    const seedsContainer = $("#seedsContainer");
    let html = "";
    
    seedsData.forEach((seed, index) => {
        let savedPrice = localStorage.getItem("price" + seed.id) || "1";
        let savedAmt = localStorage.getItem("amt" + seed.id) || "200";

        // Animation delay for cascading load effect using the CSS we added
        html += `
        <div class="seed" style="animation-delay: ${index * 0.01}s">
            <div>
                <img src="${seed.img}">
                <input type="number" id="amt${seed.id}" value="${savedAmt}" placeholder="0">
            </div>
            <div>
                <label for="price${seed.id}">Price: </label>
                <input type="number" id="price${seed.id}" value="${savedPrice}" placeholder="0">
                <p>/</p>
                <img src="images/worldlock.png">
            </div>
        </div>
        `;
    });
    
    seedsContainer.html(html);

    // Save values to localStorage on change
    seedsContainer.on('input', 'input[type="number"]', function() {
        localStorage.setItem($(this).attr('id'), $(this).val());
    });

    // Load and save SSP Cost caching
    if (localStorage.getItem("sspCost")) {
        $("#sspCost").val(localStorage.getItem("sspCost"));
    }
    $("#sspCost").on('input', function() {
        localStorage.setItem("sspCost", $(this).val());
    });

    $("button#calculateBtn").click(function () {
        totalSSP = 0;
        totalWorldLock = 0;

        seedsData.forEach(seed => {
            calcFace(seed.id);
        });

        const sspCost = parseFloat($("#sspCost").val()) || 0;
        const totalCost = (totalSSP / 200) * sspCost;
        const cleanProfit = totalWorldLock - totalCost;

        $("#sspAmount").text("= " + parseFloat(totalSSP).toFixed(2));
        $("#wlAmount").text("= " + parseFloat(totalWorldLock).toFixed(2));
        $("#profitAmount").text("= " + parseFloat(cleanProfit).toFixed(2));
        
        if (cleanProfit >= 0) {
            $("#profitAmount").css("color", "#10b981");
        } else {
            $("#profitAmount").css("color", "#ef4444");
        }
    });
});

function calcFace(idName) {
    const amountId = "#amt" + idName;
    const priceId = "#price" + idName;

    const amountNb = $(amountId).val();
    const priceNb = $(priceId).val();

    if (priceNb > 0) {
        if (amountNb > 0) {
            let tempTotalWorldLock = amountNb / priceNb;
            totalWorldLock = totalWorldLock + tempTotalWorldLock;
            $(priceId).css("background-color", "rgba(0, 0, 0, 0.25)"); 
        }

        const exisistingText = $("#noPrice").text();
        if (exisistingText.includes(" " + idName + ", ")) {
            const newText = exisistingText.replace(idName + ", ", "");
            $("#noPrice").text(newText);
        }

    } else {
        if (amountNb > 0) {
            $(priceId).css("background-color", "rgba(220, 38, 38, 0.5)"); 
            const exisistingText = $("#noPrice").text();

            if (!exisistingText.includes(" " + idName + ", ")) {
                $("#noPrice").text(exisistingText + idName + ", ");
            }
        } else {
            const exisistingText = $("#noPrice").text();
            if (exisistingText.includes(" " + idName + ", ")) {
                const newText = exisistingText.replace(idName + ", ", "");
                $("#noPrice").text(newText);
            }
            $(priceId).css("background-color", "rgba(0, 0, 0, 0.25)");
        }
    }

    let amt = parseFloat(amountNb) || 0;
    let tempssp = amt / 5;
    totalSSP = totalSSP + tempssp;
}